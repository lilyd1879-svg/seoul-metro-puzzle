def place_chain(stations, anchors):
    pinned = {}
    for i, st in enumerate(stations):
        if st in STATIONS:
            pinned[i] = (STATIONS[st][0] / SCALE, STATIONS[st][1] / SCALE)
    for st_name, px, py in anchors:
        if st_name in stations:
            idx = stations.index(st_name)
            pinned[idx] = (px, py)
            _set_pt(st_name, px, py)

    sorted_idxs = sorted(pinned.keys())
    if not sorted_idxs:
        return
    for a, b in zip(sorted_idxs[:-1], sorted_idxs[1:]):
        x1, y1 = pinned[a]
        x2, y2 = pinned[b]
        steps = b - a
        for k in range(1, steps):
            t = k / steps
            px = x1 + (x2 - x1) * t
            py = y1 + (y2 - y1) * t
            _set_pt(stations[a + k], px, py)

