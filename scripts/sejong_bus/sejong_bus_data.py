# Build GEUMGANG_CROSSINGS automatically from all edges connecting NORTH_BANK and SOUTH_BANK
GEUMGANG_CROSSINGS = set()
for _line, _seq in LINES.items():
    for _i in range(len(_seq) - 1):
        _u, _v = _seq[_i], _seq[_i + 1]
        if (_u in NORTH_BANK and _v in SOUTH_BANK) or (_u in SOUTH_BANK and _v in NORTH_BANK):
            GEUMGANG_CROSSINGS.add((_u, _v))
            GEUMGANG_CROSSINGS.add((_v, _u))

# Sanity check that all stops in LINES exist in STOPS_COORDS and are classified in NORTH_BANK or SOUTH_BANK
for _line, _seq in LINES.items():
    for _s in _seq:
        assert _s in STOPS_COORDS, f"Missing coords for {_s}"
        assert (_s in NORTH_BANK) ^ (_s in SOUTH_BANK), f"Stop {_s} must be in exactly one bank"
